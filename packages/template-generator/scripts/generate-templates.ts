import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import isBinaryPath from "is-binary-path";
import { glob } from "tinyglobby";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const TEMPLATES_DIR = path.join(__dirname, "../templates");
const OUTPUT_FILE = path.join(__dirname, "../src/templates.generated.ts");
const BINARY_OUTPUT_DIR = path.join(__dirname, "../templates-binary");

async function generateTemplates() {
  console.log("📦 Generating embedded templates...");

  const files = await glob("**/*", { cwd: TEMPLATES_DIR, dot: true, onlyFiles: true });

  // Sort files alphabetically for deterministic output (minimizes git diffs)
  files.sort((a, b) => a.localeCompare(b));

  console.log(`📂 Found ${files.length} template files`);

  const entries: string[] = [];
  const binaryFiles: string[] = [];
  const applicationEntries: [string, string][] = [];
  const moduleEntries: [string, string][] = [];
  const builderEntries: [string, string][] = [];

  for (const file of files) {
    const fullPath = path.join(TEMPLATES_DIR, file);
    const normalizedPath = file.replace(/\\/g, "/");
    if (/^modules\/(?:[^/]+\/module|presets)\.json$/.test(normalizedPath)) {
      moduleEntries.push([normalizedPath, fs.readFileSync(fullPath, "utf-8")]);
    }
    if (normalizedPath === "builder.json") {
      builderEntries.push([normalizedPath, fs.readFileSync(fullPath, "utf-8")]);
    }
    if (/^(apps|frontend|backend|cli)\//.test(normalizedPath)) {
      const metadata = /\/(app|adapter)\.json$/.test(normalizedPath);
      const content = isBinaryPath(file) ? "[binary]" : fs.readFileSync(fullPath, "utf-8");
      applicationEntries.push([
        normalizedPath,
        metadata ? content : content.trim() ? "[implementation]" : "",
      ]);
    }

    if (isBinaryPath(file)) {
      binaryFiles.push(normalizedPath);
      entries.push(`  ["${normalizedPath}", \`[Binary file]\`]`);
    } else {
      const content = fs.readFileSync(fullPath, "utf-8");
      const escapedContent = content
        .replace(/\\/g, "\\\\")
        .replace(/`/g, "\\`")
        .replace(/\$\{/g, "\\${");
      entries.push(`  ["${normalizedPath}", \`${escapedContent}\`]`);
    }
  }

  const output = `// Auto-generated - DO NOT EDIT
// Run 'bun run generate-templates' to regenerate

export const EMBEDDED_TEMPLATES: Map<string, string> = new Map([
${entries.join(",\n")}
]);

export const TEMPLATE_COUNT = ${files.length};
`;

  fs.writeFileSync(OUTPUT_FILE, output);
  fs.writeFileSync(
    path.join(__dirname, "../src/applications.generated.ts"),
    `// Auto-generated by scripts/generate-templates.ts. Metadata and real implementation inventory only.\nexport const APPLICATION_TEMPLATES: Map<string, string> = new Map(${JSON.stringify(applicationEntries, null, 2)});\n`,
  );
  for (const [name, symbol, metadata] of [
    ["modules", "MODULE_METADATA", moduleEntries],
    ["builder", "BUILDER_METADATA", builderEntries],
  ] as const) {
    fs.writeFileSync(
      path.join(__dirname, `../src/${name}.generated.ts`),
      `// Auto-generated by scripts/generate-templates.ts. Template metadata only.\nexport const ${symbol}: Map<string, string> = new Map(${JSON.stringify(metadata, null, 2)});\n`,
    );
  }

  const stats = fs.statSync(OUTPUT_FILE);
  const sizeMB = (stats.size / (1024 * 1024)).toFixed(2);

  console.log(`✅ Generated ${OUTPUT_FILE}`);
  console.log(`📊 File size: ${sizeMB} MB (${files.length} templates)`);

  await copyBinaryFiles(binaryFiles);
}

async function copyBinaryFiles(binaryFiles: string[]) {
  // Sort for deterministic output
  binaryFiles.sort((a, b) => a.localeCompare(b));

  console.log(`\n📁 Copying ${binaryFiles.length} binary files to templates-binary/...`);

  if (fs.existsSync(BINARY_OUTPUT_DIR)) {
    fs.rmSync(BINARY_OUTPUT_DIR, { recursive: true });
  }

  let totalSize = 0;

  for (const file of binaryFiles) {
    const srcPath = path.join(TEMPLATES_DIR, file);
    const destPath = path.join(BINARY_OUTPUT_DIR, file);

    fs.mkdirSync(path.dirname(destPath), { recursive: true });

    fs.copyFileSync(srcPath, destPath);

    totalSize += fs.statSync(destPath).size;
  }

  const sizeKB = (totalSize / 1024).toFixed(2);
  console.log(`✅ Copied ${binaryFiles.length} binary files (${sizeKB} KB)`);
}

generateTemplates().catch((err) => {
  console.error("❌ Failed to generate templates:", err);
  process.exit(1);
});
