import { createHash } from "node:crypto";
import { constants } from "node:fs";
import * as fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { isDeepStrictEqual } from "node:util";

import {
  EMBEDDED_TEMPLATES,
  generate,
  type VirtualFileTree,
  type VirtualNode,
} from "@xstack/template-generator";
import { writeTree } from "@xstack/template-generator/fs-writer";
import { ProjectConfigSchema, type ProjectConfig } from "@xstack/types";
import { Result, TaggedError } from "better-result";
import z from "zod";

import { formatCode } from "../../utils/file-formatter";

export class ModuleAddError extends TaggedError("ModuleAddError")<{
  message: string;
  cause?: unknown;
}> {}

const StoredFileSchema = z.strictObject({
  content: z.string(),
  encoding: z.enum(["utf8", "base64"]),
  hash: z.string().regex(/^[a-f0-9]{64}$/),
});
const BaselineSchema = z.strictObject({
  format: z.literal(1),
  generatorVersion: z.string().min(1),
  config: ProjectConfigSchema,
  files: z.record(z.string(), StoredFileSchema),
  checksum: z.string().regex(/^[a-f0-9]{64}$/),
});
export type Baseline = z.infer<typeof BaselineSchema>;
export const BASELINE_PATH = ".xstack/baseline/manifest.json";
export interface FileChange {
  path: string;
  before?: Buffer;
  after?: Buffer;
  mode?: number;
}

export function isSecretPath(filePath: string): boolean {
  return filePath
    .split("/")
    .some((part) => part !== ".env.schema" && /^\.env(?:\.|$)|^\.dev\.vars(?:\.|$)/.test(part));
}

/** The baseline is only generated bytes, never a snapshot of the live project. */
export function baselineConfig(config: ProjectConfig): ProjectConfig {
  return ProjectConfigSchema.parse({
    ...config,
    projectDir: ".",
    relativePath: ".",
    install: false,
    git: false,
  });
}

export function assertRelativePath(filePath: string): void {
  if (
    !filePath ||
    filePath.includes("\\") ||
    filePath.includes("\0") ||
    path.posix.isAbsolute(filePath) ||
    filePath.split("/").some((part) => !part || part === "." || part === "..") ||
    /^[A-Za-z]:/.test(filePath)
  ) {
    throw new ModuleAddError({ message: `Unsafe generated path: ${filePath}` });
  }
}

/** Reject symbolic links in every existing component, including the project root. */
export async function assertSafePath(root: string, relative: string): Promise<void> {
  assertRelativePath(relative);
  const resolved = path.resolve(root);
  let current = path.parse(resolved).root;
  for (const part of [
    ...resolved.slice(current.length).split(path.sep).filter(Boolean),
    ...relative.split("/"),
  ]) {
    current = path.join(current, part);
    try {
      const stat = await fs.lstat(current);
      if (stat.isSymbolicLink())
        throw new ModuleAddError({ message: `Refusing symbolic link: ${current}` });
    } catch (cause) {
      if (cause instanceof Error && "code" in cause && cause.code === "ENOENT") return;
      throw cause;
    }
  }
}

export async function readProjectFile(root: string, relative: string): Promise<Buffer | undefined> {
  await assertSafePath(root, relative);
  let handle;
  try {
    handle = await fs.open(path.join(root, relative), constants.O_RDONLY | constants.O_NOFOLLOW);
    const stat = await handle.stat();
    if (!stat.isFile())
      throw new ModuleAddError({ message: `Expected a regular file: ${relative}` });
    return await handle.readFile();
  } catch (cause) {
    if (cause instanceof Error && "code" in cause && cause.code === "ENOENT") return undefined;
    throw cause;
  } finally {
    await handle?.close();
  }
}

export async function prepareGeneratedTree(
  tree: VirtualFileTree,
  packageManagerVersion?: string,
): Promise<void> {
  const visit = async (node: VirtualNode): Promise<void> => {
    if (node.type === "directory") {
      for (const child of node.children) await visit(child);
      return;
    }
    assertRelativePath(node.path);
    if (node.path.startsWith(".xstack/"))
      throw new ModuleAddError({ message: "Templates may not write reserved .xstack state" });
    if (node.content === "[Binary file]" || isSecretPath(node.path)) return;
    if (node.path === "package.json" && packageManagerVersion) {
      const pkg = z.record(z.string(), z.json()).parse(JSON.parse(node.content));
      pkg.packageManager = `${tree.config.packageManager}@${packageManagerVersion}`;
      node.content = JSON.stringify(pkg, null, 2);
    }
    node.content = (await formatCode(node.path, node.content)) ?? node.content;
  };
  await visit(tree.root);
}

export async function generatedFiles(tree: VirtualFileTree): Promise<Map<string, Buffer>> {
  const temporary = await fs.realpath(
    await fs.mkdtemp(path.join(os.tmpdir(), "xstack-generation-")),
  );
  try {
    const written = await writeTree(tree, temporary);
    if (written.isErr()) throw written.error;
    const files = new Map<string, Buffer>();
    const visit = async (node: VirtualNode): Promise<void> => {
      if (node.type === "directory") {
        for (const child of node.children) await visit(child);
        return;
      }
      const content = await readProjectFile(temporary, node.path);
      if (!content)
        throw new ModuleAddError({ message: `Generated binary unavailable: ${node.path}` });
      files.set(node.path, content);
    };
    await visit(tree.root);
    return files;
  } finally {
    await fs.rm(temporary, { recursive: true, force: true });
  }
}

export function createBaseline(
  config: ProjectConfig,
  version: string,
  files: Map<string, Buffer>,
): Baseline {
  const stored: Baseline["files"] = Object.create(null);
  for (const [filePath, bytes] of [...files.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    assertRelativePath(filePath);
    if (isSecretPath(filePath) || filePath === "xstack.jsonc") continue;
    if (filePath.startsWith(".xstack/"))
      throw new ModuleAddError({ message: "Reserved baseline path in generated output" });
    const text = bytes.toString("utf8");
    const encoding = !bytes.includes(0) && Buffer.from(text).equals(bytes) ? "utf8" : "base64";
    stored[filePath] = {
      content: bytes.toString(encoding),
      encoding,
      hash: createHash("sha256").update(bytes).digest("hex"),
    };
  }
  const payload = {
    format: 1 as const,
    generatorVersion: version,
    config: baselineConfig(config),
    files: stored,
  };
  return {
    ...payload,
    checksum: createHash("sha256").update(JSON.stringify(payload)).digest("hex"),
  };
}

export async function loadBaseline(projectDir: string): Promise<Baseline | undefined> {
  const bytes = await readProjectFile(projectDir, BASELINE_PATH);
  if (!bytes) return undefined;
  const baseline = BaselineSchema.parse(JSON.parse(bytes.toString("utf8")));
  const { checksum, ...payload } = baseline;
  if (createHash("sha256").update(JSON.stringify(payload)).digest("hex") !== checksum)
    throw new ModuleAddError({
      message:
        "Baseline metadata checksum mismatch; restore .xstack/baseline from version control.",
    });
  for (const [filePath, stored] of Object.entries(baseline.files)) {
    assertRelativePath(filePath);
    if (isSecretPath(filePath) || filePath.startsWith(".xstack/") || filePath === "xstack.jsonc")
      throw new ModuleAddError({ message: `Forbidden baseline entry: ${filePath}` });
    if (
      createHash("sha256").update(Buffer.from(stored.content, stored.encoding)).digest("hex") !==
      stored.hash
    )
      throw new ModuleAddError({ message: `Baseline content checksum mismatch: ${filePath}` });
  }
  return baseline;
}

export async function saveCreationBaseline(tree: VirtualFileTree, version: string): Promise<void> {
  const baseline = createBaseline(tree.config, version, await generatedFiles(tree));
  await assertSafePath(tree.config.projectDir, BASELINE_PATH);
  await fs.mkdir(path.join(tree.config.projectDir, ".xstack/baseline"), { recursive: true });
  await fs.writeFile(
    path.join(tree.config.projectDir, BASELINE_PATH),
    `${JSON.stringify(baseline, null, 2)}\n`,
    { flag: "wx", mode: 0o600 },
  );
}

export async function regenerate(
  config: ProjectConfig,
  version: string,
): Promise<Map<string, Buffer>> {
  const generated = await generate({ config, version, templates: EMBEDDED_TEMPLATES });
  if (generated.isErr()) throw generated.error;
  await prepareGeneratedTree(generated.value);
  return generatedFiles(generated.value);
}

const JournalSchema = z.strictObject({
  state: z.enum(["prepared", "committed"]),
  changes: z.array(
    z.strictObject({
      path: z.string(),
      before: z.string().optional(),
      after: z.string().optional(),
      mode: z.number().int().optional(),
    }),
  ),
});

/** Refuse recovery over edits made after an interrupted operation. */
async function recoverTransaction(projectDir: string): Promise<void> {
  const journalBytes = await readProjectFile(projectDir, ".xstack/transaction/journal.json");
  if (!journalBytes) return;
  const journal = JournalSchema.parse(JSON.parse(journalBytes.toString("utf8")));
  if (journal.state === "prepared") {
    for (const [index, change] of journal.changes.entries()) {
      assertRelativePath(change.path);
      if (change.path.startsWith(".xstack/") && change.path !== BASELINE_PATH)
        throw new ModuleAddError({ message: "Unsafe transaction journal path" });
      const current = await readProjectFile(projectDir, change.path);
      const before = change.before === undefined ? undefined : Buffer.from(change.before, "base64");
      const after = change.after === undefined ? undefined : Buffer.from(change.after, "base64");
      const displaced =
        current === undefined
          ? await readProjectFile(projectDir, `.xstack/transaction/original-${index}`)
          : undefined;
      if (current === undefined && before !== undefined && isDeepStrictEqual(displaced, before))
        continue;
      if (!isDeepStrictEqual(current, before) && !isDeepStrictEqual(current, after))
        throw new ModuleAddError({
          message: `Interrupted module addition overlaps newer edits in ${change.path}. Save your edits, restore this file from the transaction journal, and rerun.`,
        });
    }
    for (const change of [...journal.changes].reverse()) {
      await assertSafePath(projectDir, change.path);
      const target = path.join(projectDir, change.path);
      if (change.before === undefined) await fs.rm(target, { force: true });
      else {
        await fs.mkdir(path.dirname(target), { recursive: true });
        await fs.writeFile(target, Buffer.from(change.before, "base64"), {
          mode: change.mode ?? 0o600,
        });
      }
    }
  }
  await fs.rm(path.join(projectDir, ".xstack/transaction"), { recursive: true, force: true });
}

export async function withModuleLock<T>(
  projectDir: string,
  dryRun: boolean,
  operation: () => Promise<T>,
): Promise<T> {
  await assertSafePath(projectDir, ".xstack/lock");
  if (dryRun) {
    if (await readProjectFile(projectDir, ".xstack/lock"))
      throw new ModuleAddError({
        message: "A module operation is active or interrupted; rerun without --dry-run to recover.",
      });
    if (await readProjectFile(projectDir, ".xstack/transaction/journal.json"))
      throw new ModuleAddError({
        message: "An interrupted module addition needs recovery; rerun without --dry-run.",
      });
    return operation();
  }
  await fs.mkdir(path.join(projectDir, ".xstack"), { recursive: true });
  const lockPath = path.join(projectDir, ".xstack/lock");
  const existing = await readProjectFile(projectDir, ".xstack/lock");
  if (existing) {
    const pid = z
      .number()
      .int()
      .positive()
      .parse(Number(existing.toString("utf8")));
    let alive = true;
    try {
      process.kill(pid, 0);
    } catch (cause) {
      if (cause instanceof Error && "code" in cause && cause.code === "ESRCH") alive = false;
      else throw cause;
    }
    if (alive)
      throw new ModuleAddError({ message: "Another module addition is running in this project." });
    await fs.unlink(lockPath);
  }
  const lock = await fs.open(lockPath, "wx", 0o600);
  try {
    await lock.writeFile(String(process.pid));
    await lock.sync();
    await recoverTransaction(projectDir);
    return await operation();
  } finally {
    await lock.close();
    await fs.unlink(lockPath);
  }
}

/** Stage the complete journal before changing any project file; install runs only afterwards. */
export async function applyModuleChanges(projectDir: string, changes: FileChange[]): Promise<void> {
  if (!changes.length) return;
  for (const change of changes) {
    const current = await readProjectFile(projectDir, change.path);
    if (!isDeepStrictEqual(current, change.before))
      throw new ModuleAddError({
        message: `File changed while planning: ${change.path}; retry the addition.`,
      });
    if (current) change.mode = (await fs.lstat(path.join(projectDir, change.path))).mode & 0o777;
  }
  const transactionDir = path.join(projectDir, ".xstack/transaction");
  await assertSafePath(projectDir, ".xstack/transaction/journal.json");
  await fs.mkdir(transactionDir, { mode: 0o700 });
  const journal: z.infer<typeof JournalSchema> = {
    state: "prepared",
    changes: changes.map((change) => ({
      path: change.path,
      before: change.before?.toString("base64"),
      after: change.after?.toString("base64"),
      mode: change.mode,
    })),
  };
  const journalPath = path.join(transactionDir, "journal.json");
  const handle = await fs.open(journalPath, "wx", 0o600);
  try {
    await handle.writeFile(JSON.stringify(journal));
    await handle.sync();
  } finally {
    await handle.close();
  }
  try {
    for (const [index, change] of changes.entries()) {
      if (!isDeepStrictEqual(await readProjectFile(projectDir, change.path), change.before))
        throw new ModuleAddError({ message: `Concurrent edit detected: ${change.path}` });
      const target = path.join(projectDir, change.path);
      await fs.mkdir(path.dirname(target), { recursive: true });
      await assertSafePath(projectDir, change.path);
      if (change.before !== undefined) {
        const displacedPath = `.xstack/transaction/original-${index}`;
        await fs.rename(target, path.join(projectDir, displacedPath));
        const displaced = await readProjectFile(projectDir, displacedPath);
        if (!isDeepStrictEqual(displaced, change.before)) {
          // Never discard the edit that raced the initial comparison.
          await fs.link(path.join(projectDir, displacedPath), target);
          throw new ModuleAddError({
            message: `Concurrent edit detected while replacing ${change.path}; the newer file was preserved.`,
          });
        }
      }
      if (change.after === undefined) continue;
      const staged = path.join(transactionDir, `next-${index}`);
      const stagedHandle = await fs.open(
        staged,
        "wx",
        change.mode ?? (isSecretPath(change.path) ? 0o600 : 0o644),
      );
      try {
        await stagedHandle.writeFile(change.after);
        await stagedHandle.sync();
      } finally {
        await stagedHandle.close();
      }
      await assertSafePath(projectDir, change.path);
      // link is exclusive, unlike rename: a file created by another writer wins.
      await fs.link(staged, target);
      await fs.unlink(staged);
    }
    journal.state = "committed";
    const committed = path.join(transactionDir, "committed.json");
    await fs.writeFile(committed, JSON.stringify(journal), { mode: 0o600, flag: "wx" });
    await fs.rename(committed, journalPath);
  } catch (cause) {
    try {
      await recoverTransaction(projectDir);
    } catch (recoveryCause) {
      throw new ModuleAddError({
        message: `Addition failed and automatic rollback was blocked by a concurrent edit. Preserve .xstack/transaction for recovery. ${recoveryCause instanceof Error ? recoveryCause.message : String(recoveryCause)}`,
        cause,
      });
    }
    throw cause;
  }
  await fs.rm(transactionDir, { recursive: true, force: true });
}

export function moduleResult<T>(operation: () => Promise<T>): Promise<Result<T, ModuleAddError>> {
  return Result.tryPromise({
    try: operation,
    catch: (cause) =>
      ModuleAddError.is(cause)
        ? cause
        : new ModuleAddError({
            message: cause instanceof Error ? cause.message : String(cause),
            cause,
          }),
  });
}
